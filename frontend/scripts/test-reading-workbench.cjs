// Real PDF rendering and reader interaction against tests/e2e/reader_fixture_server.py.
// All fixtures and screenshots live under /tmp; no real models or private uploads.
const { chromium, request } = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const fixture = JSON.parse(fs.readFileSync('/tmp/paper-reader-e2e.json', 'utf8'));
  const api = await request.newContext({ baseURL: 'http://127.0.0.1:8107' });
  const opened = await api.post('/api/v1/reader/open', { data: { attachment_id: fixture.attachment.id } });
  assert.equal(opened.status(), 200);
  const bound = await opened.json();
  const browser = await chromium.launch({ headless: true });
  const main = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await main.goto(`http://127.0.0.1:3107/chat?history=${encodeURIComponent(bound.history_filename)}`, { waitUntil: 'networkidle', timeout: 90000 });
  await main.getByPlaceholder('输入你的问题...').fill('保留主聊天草稿');
  await main.getByRole('button', { name: '收起右边栏' }).click();
  await main.getByRole('button', { name: '打开工作台空间' }).click();
  await main.getByRole('heading', { name: '阅研 · 阅读空间' }).waitFor();
  const popup = main.waitForEvent('popup');
  await main.getByRole('button', { name: '打开阅读工作台', exact: true }).click();
  const page = await popup;
  await page.waitForURL(`**/chat/${bound.session_id}/read/${fixture.attachment.id}`, { timeout: 30000 });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.waitForLoadState('networkidle');
  await page.locator('[data-pdf-page="1"] .reader-text-layer span').first().waitFor({ timeout: 45000 });
  await page.screenshot({ path: '/tmp/paper-reader-initial.png', fullPage: true });
  const selected = await page.evaluate(() => {
    const span = [...document.querySelectorAll('[data-pdf-page="1"] .reader-text-layer span')].find(n => n.textContent.startsWith('Our model may improve'));
    if (!span) return false;
    const range = document.createRange(); range.selectNodeContents(span);
    const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range);
    span.dispatchEvent(new MouseEvent('mouseup', { bubbles: true }));
    return span.textContent;
  });
  assert.ok(selected, 'PDF text layer supports selection');
  await page.getByRole('toolbar', { name: '选文操作' }).waitFor();
  assert.equal(await page.locator('.reader-context').count(), 0);
  assert.equal(await page.locator('.reader-current-selection span').first().evaluate(n => getComputedStyle(n).borderBottomStyle), 'dashed');
  await page.getByRole('button', { name: '翻译', exact: true }).click();
  await page.getByText('在固定条件下，我们的模型可能提高准确率。', { exact: false }).first().waitFor({ timeout: 30000 });
  await page.locator('.reader-answer .katex').first().waitFor();
  await page.screenshot({ path: '/tmp/paper-reader-translation.png', fullPage: true });
  await page.getByRole('button', { name: '记为发现', exact: true }).click();
  await page.getByRole('textbox', { name: '我的阅读笔记' }).fill('需要验证变化数据分布；保留限定条件。');
  await page.getByRole('button', { name: '附解释保存', exact: true }).click();
  await page.locator('.reader-finding').first().waitFor();
  await page.getByRole('button', { name: '带回对话', exact: true }).click();
  await page.getByText('已带回主对话，可以继续比较、写作或汇报').waitFor();
  const history = await api.get('/api/v1/chat/history/' + encodeURIComponent(bound.history_filename));
  const data = await history.json();
  assert.ok(data.messages.some(m => m.content.includes('需要验证变化数据分布')));
  await main.getByRole('link', { name: '返回原文', exact: true }).waitFor();
  assert.equal(await main.getByPlaceholder('输入你的问题...').inputValue(), '保留主聊天草稿');
  const sourcePopup = main.waitForEvent('popup');
  await main.getByRole('link', { name: '返回原文', exact: true }).click();
  const sourcePage = await sourcePopup;
  await sourcePage.locator('.reader-highlights span.active').first().waitFor({ timeout: 30000 });
  assert.equal(await sourcePage.getByRole('spinbutton', { name: '跳转页码' }).inputValue(), '1');
  await sourcePage.waitForTimeout(1000);
  await sourcePage.close();
  await page.getByRole('button', { name: '助读', exact: true }).click();
  await page.getByRole('textbox', { name: '阅读问题' }).fill('为什么这里需要固定条件？');
  await page.getByRole('button', { name: '提问', exact: true }).click();
  await page.locator('.reader-thread-message.assistant').first().waitFor({ timeout: 30000 });
  assert.equal((await (await api.get('/api/v1/chat/history/' + encodeURIComponent(bound.history_filename))).json()).messages.length, data.messages.length);
  await page.getByRole('button', { name: '放大', exact: true }).click();
  await page.waitForTimeout(1000);
  await page.getByRole('button', { name: '下一页', exact: true }).click();
  await page.waitForTimeout(1100);
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.getByRole('spinbutton', { name: '跳转页码' }).inputValue(), '2');
  await page.getByRole('button', { name: /我的发现/ }).click();
  await page.locator('.reader-finding').first().waitFor();
  await page.screenshot({ path: '/tmp/paper-reader-findings.png', fullPage: true });
  await page.getByRole('spinbutton', { name: '跳转页码' }).fill('3');
  await page.locator('[data-pdf-page="3"] .reader-text-layer span').first().waitFor();
  const rotated = await page.evaluate(() => {
    const span = [...document.querySelectorAll('[data-pdf-page="3"] .reader-text-layer span')].find(n => n.textContent.startsWith('Rotation must'));
    const range = document.createRange(); range.selectNodeContents(span);
    window.getSelection().removeAllRanges(); window.getSelection().addRange(range);
    span.dispatchEvent(new MouseEvent('mouseup', { bubbles: true }));
    return !!span;
  });
  assert.ok(rotated);
  await page.getByRole('button', { name: '划线', exact: true }).click();
  await page.getByText('已保存划线', { exact: true }).waitFor();
  await page.locator('[data-pdf-page="3"] .reader-highlights span.active').first().waitFor();
  const aligned = await page.evaluate(() => {
    const span = [...document.querySelectorAll('[data-pdf-page="3"] .reader-text-layer span')].find(n => n.textContent.startsWith('Rotation must'));
    const text = span.getBoundingClientRect();
    const mark = document.querySelector('[data-pdf-page="3"] .reader-highlights span.active').getBoundingClientRect();
    return Math.abs(text.x + text.width / 2 - mark.x - mark.width / 2) < 12 && Math.abs(text.y + text.height / 2 - mark.y - mark.height / 2) < 12;
  });
  assert.ok(aligned, 'rotated selection and saved highlight align');
  assert.equal(await page.locator('[data-pdf-page="3"] .reader-highlights span.saved').first().evaluate(n => getComputedStyle(n).borderBottomStyle), 'solid');
  await page.keyboard.press('Escape');
  await page.getByRole('spinbutton', { name: '跳转页码' }).fill('4');
  await page.getByRole('button', { name: '助读', exact: true }).click();
  await page.getByRole('textbox', { name: '阅读问题' }).fill('这一页没有文本，应该如何继续？');
  await page.getByRole('button', { name: '提问', exact: true }).click();
  await page.locator('.reader-thread-message.assistant').first().waitFor();
  await page.getByRole('button', { name: '框选图片', exact: true }).click();
  const regionLayer = page.locator('[data-pdf-page="4"] .reader-region-selector');
  await regionLayer.scrollIntoViewIfNeeded();
  const regionBox = await regionLayer.boundingBox();
  await page.mouse.move(regionBox.x + 40, regionBox.y + 60);
  await page.mouse.down(); await page.mouse.move(regionBox.x + 190, regionBox.y + 180, { steps: 8 }); await page.mouse.up();
  await page.getByRole('button', { name: '标记区域', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: '翻译', exact: true }).count(), 0);
  await page.getByRole('button', { name: '标记区域', exact: true }).click();
  await page.locator('[data-pdf-page="4"] .reader-highlights span.saved.region').waitFor();
  await page.waitForTimeout(1100);
  await page.reload({ waitUntil: 'networkidle' });
  await page.locator('[data-pdf-page="4"] .reader-highlights span.saved.region').waitFor();
  await page.screenshot({ path: '/tmp/paper-reader-region.png', fullPage: true });
  await page.waitForTimeout(1000);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload({ waitUntil: 'networkidle' });
  await page.screenshot({ path: '/tmp/paper-reader-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const uploadTab = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  let chatCalls = 0;
  uploadTab.on('request', req => { if (req.url().includes('/chat/stream')) chatCalls++; });
  await uploadTab.goto('http://127.0.0.1:3107/chat', { waitUntil: 'networkidle' });
  await uploadTab.locator('input[type=file]').setInputFiles({ name: '从上传开始阅读.pdf', mimeType: 'application/pdf',
    buffer: fs.readFileSync(`${fixture.data_dir}/uploads/${fixture.attachment.id}.pdf`) });
  await uploadTab.getByRole('button', { name: '只上传，开始阅读', exact: true }).click();
  const uploadPopup = uploadTab.waitForEvent('popup');
  await uploadTab.getByRole('button', { name: '打开阅读工作台', exact: true }).first().click();
  const uploadedReader = await uploadPopup;
  await uploadedReader.locator('[data-pdf-page="1"] .reader-text-layer span').first().waitFor({timeout: 30000});
  assert.equal(chatCalls, 0, 'upload-only reading never sends a chat/LLM turn');
  await uploadedReader.waitForTimeout(1000);
  await uploadedReader.close(); await uploadTab.close();
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ ok: true, checks: ['dedicated workbench sidebar entry, draft preservation and source return', 'PDF rendering and selectable original text', 'contextual translation and math', 'finding persistence and publication', 'separate reading discussion', 'zoom/page recovery', 'dashed selection, solid underline, rotated alignment and blank-page question', 'region selection persistence', 'mobile overflow', 'upload-only reading without chat turn'], screenshots: ['/tmp/paper-reader-initial.png', '/tmp/paper-reader-translation.png', '/tmp/paper-reader-findings.png', '/tmp/paper-reader-mobile.png'] }, null, 2));
  await browser.close(); await api.dispose();
})().catch(e => { console.error(e); process.exit(1); });
